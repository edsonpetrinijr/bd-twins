"""Generates spot/spot.xml.

Sources (details in docs/spot-sources.md):
- BD spot-specifications.pdf: 32.7 kg with battery, battery 5.2 kg, 1.10 x 0.50 m, walking height 0.52-0.70 m,
  14 kg payload, 1.6 m/s.
- Joint layout, limits, torques and per-link leg masses: RAI Institute spot_description (MIT license).
- Visual shapes: our own CAD (spot/cad.py) drawn from BD photos and videos.
"""

from pathlib import Path

HIP_X, HIP_Y, HIP_OUT = 0.29785, 0.055, 0.110945   # hip abduction joint position, then upper-leg offset
KNEE = (0.025, -0.3205)                             # knee (x, z) from the hip pitch joint
SHIN = 0.3365                                       # knee to foot center
FOOT_R = 0.036
MASS = {"body": 32.7 - 4 * (1.68 + 2.34 + 0.35), "hip": 1.68, "upper": 2.34, "lower": 0.35}
STAND = {"hip_y": 0.85, "knee": -1.65}              # standing pose: thighs leaning like in the BD videos, body top ~0.58 m


def g(kind, cls="visual", **kw):
    attrs = " ".join(f'{k}="{v}"' for k, v in kw.items())
    return f'<geom class="{cls}" type="{kind}" {attrs}/>'


def mesh(name, material, pos="0 0 0", euler="0 0 0"):
    return g("mesh", mesh=name, material=material, pos=pos, euler=euler)


def leg(name, fx, s):
    """fx: +1 front / -1 rear; s: +1 left / -1 right."""
    flip = "0 0 3.14159265" if s < 0 else "0 0 0"
    return f"""
      <body name="{name}_hip" pos="{fx*HIP_X} {s*HIP_Y} 0">
        <joint name="{name}_hip_x" axis="1 0 0" range="-0.785 0.785"/>
        {g("capsule", "collision", name=f"{name}_hip_collision", fromto="-0.05 0 0 0.05 0 0", size="0.05", mass=MASS["hip"])}
        {mesh("hip_motor", "frame", "0 0 0", flip)}
        <body name="{name}_upper_leg" pos="0 {s*HIP_OUT} 0">
          <joint name="{name}_hip_y" axis="0 1 0" range="-0.899 2.295"/>
          {g("capsule", "collision", name=f"{name}_upper_collision", fromto=f"0 0 0 {KNEE[0]} 0 {KNEE[1]}", size="0.04", mass=MASS["upper"])}
          {mesh("upper_cover", "shell", f"0 {s*0.005} 0")}
          {mesh("upper_motor", "frame", euler=flip)}
          <body name="{name}_lower_leg" pos="{KNEE[0]} 0 {KNEE[1]}">
            <joint name="{name}_knee" axis="0 1 0" range="-2.7929 -0.2548"/>
            {g("capsule", "collision", name=f"{name}_shin_collision", fromto=f"0 0 -0.03 0 0 -{SHIN - 0.04}", size="0.022", mass=MASS["lower"] - 0.1)}
            {g("sphere", "collision", name=f"{name}_foot_collision", pos=f"0 0 -{SHIN}", size=FOOT_R, mass=0.1)}
            {mesh("shin", "frame")}
            {mesh("knee", "frame", euler=flip)}
            {mesh("foot", "rubber")}
            <site name="{name}_foot" pos="0 0 -{SHIN + FOOT_R}"/>
          </body>
        </body>
      </body>"""


LEGS = (("front_left", 1, 1), ("front_right", 1, -1), ("rear_left", -1, 1), ("rear_right", -1, -1))
PARTS = ("body_shell", "side_details", "body_core", "face_front", "face_rear", "hip_motor", "upper_cover", "upper_motor",
         "shin", "foot", "knee")

XML = f"""<!--
  Spot (BD quadruped). GENERATED by spot/build.py, do not edit. Sources: docs/spot-sources.md.
  Frame: x forward, y left, z up. Collision geoms (group 3) carry the mass; visuals (group 2) are massless.
-->
<mujoco model="spot">
  <compiler angle="radian" autolimits="true" meshdir="meshes"/>

  <asset>
    <material name="shell" rgba="0.88 0.71 0.12 1" specular="0.3" shininess="0.45"/>
    <material name="frame" rgba="0.1 0.1 0.11 1" specular="0.3" shininess="0.4"/>
    <material name="face" rgba="0.04 0.04 0.05 1" specular="0.6" shininess="0.7"/>
    <material name="rubber" rgba="0.05 0.05 0.05 1" specular="0.05"/>
{chr(10).join(f'    <mesh name="{n}" file="{n}.stl"/>' for n in PARTS)}
  </asset>

  <default>
    <joint damping="0.5" armature="0.005"/>
    <site group="5" size="0.01" rgba="1 0 0 1"/>
    <default class="collision">
      <geom group="3" rgba="0.8 0.2 0.2 0.5"/>
    </default>
    <default class="visual">
      <geom group="2" contype="0" conaffinity="0" mass="0"/>
    </default>
  </default>

  <worldbody>
    <body name="body" pos="0 0 0.50">
      <freejoint name="floating_base_joint"/>
      {g("box", "collision", name="body_collision", size="0.42 0.117 0.075", mass=MASS["body"])}
      {mesh("body_shell", "shell")}
      {mesh("side_details", "frame")}
      {mesh("body_core", "frame")}
      {mesh("face_front", "face")}
      {mesh("face_rear", "face")}
      <site name="imu"/>
{"".join(leg(n, fx, s) for n, fx, s in LEGS)}
    </body>
  </worldbody>

  <contact>
{chr(10).join(f'    <exclude body1="body" body2="{n}_upper_leg"/>' for n, _, _ in LEGS)}
  </contact>

  <sensor>
    <gyro name="imu_ang_vel" site="imu"/>
    <velocimeter name="imu_lin_vel" site="imu"/>
    <accelerometer name="imu_lin_acc" site="imu"/>
    <framezaxis name="imu_upvector" objtype="body" objname="world" reftype="site" refname="imu"/>
    <subtreeangmom name="root_angmom" body="body"/>
  </sensor>
</mujoco>
"""

out = Path(__file__).parent / "spot.xml"
out.write_text(XML)
print("wrote", out)
