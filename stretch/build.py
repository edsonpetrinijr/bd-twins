"""Generates stretch/stretch.xml.

Sources (details in docs/stretch-sources.md):
- BD Stretch brochure 2026: footprint 1.0 x 1.25 m, 1,300 kg, max vertical / horizontal reach 3.2 / 1.95 m,
  23 kg cases, 16 h battery.
- Everything else (link lengths, joint layout, masses per part) is our estimate from the brochure photos.
The holonomic base is modeled as a planar joint (x, y, yaw) driven directly: Stretch's base does not tip or
step, and a fleet sim only needs it to move where it is told.
"""

from pathlib import Path

BASE_TOP = 0.6
TT = (-0.1, 0.0)            # turntable center on the base
SHOULDER_Z = 0.70           # shoulder pitch axis above the turntable bottom -> 1.30 m from the floor
UPPER, FORE = 0.75, 0.70    # to the pad center: 0.05 + 0.75 + 0.70 + 0.16 + 0.29 = 1.95 m horizontal, 1.30 + 1.90 = 3.2 m up
MASS = {"base": 1020, "turntable": 160, "shoulder": 30, "upper": 30, "fore": 20, "wrist": 10, "pad": 30}
HOME = {"turntable_yaw": 0.0, "shoulder_pitch": -2.4, "elbow_pitch": 1.8, "wrist_pitch": 0.6,
        "forearm_roll": 0.0, "wrist_yaw": 0.0, "pad_roll": 0.0}


def g(kind, cls="visual", **kw):
    attrs = " ".join(f'{k}="{v}"' for k, v in kw.items())
    return f'<geom class="{cls}" type="{kind}" {attrs}/>'


def mesh(name, material, pos="0 0 0"):
    return g("mesh", mesh=name, material=material, pos=pos)


PARTS = ("base_lower", "base_skirt", "base_deck", "corner_lights", "turntable", "turntable_band", "mast",
         "mast_light", "mast_window", "shoulder_housing", "upper_arm_shell", "upper_arm_joint", "forearm_shell",
         "forearm_joint", "wrist", "pad_plate", "pad_cups")

XML = f"""<!--
  Stretch (BD warehouse robot). GENERATED by stretch/build.py, do not edit. Sources: docs/stretch-sources.md.
  Frame: x forward, y left, z up. Collision geoms (group 3) carry the mass; visuals (group 2) are massless.
-->
<mujoco model="stretch">
  <compiler angle="radian" autolimits="true" meshdir="meshes"/>

  <asset>
    <material name="white" rgba="0.86 0.87 0.86 1" specular="0.3" shininess="0.4"/>
    <material name="frame" rgba="0.09 0.09 0.1 1" specular="0.3" shininess="0.4"/>
    <material name="amber" rgba="1 0.55 0.1 1" emission="0.6"/>
    <material name="light" rgba="0.75 0.9 1 1" emission="0.8"/>
    <material name="glass" rgba="0.05 0.06 0.08 1" specular="0.9" shininess="0.9"/>
    <material name="cups" rgba="0.18 0.2 0.18 1" specular="0.1"/>
{chr(10).join(f'    <mesh name="{n}" file="{n}.stl"/>' for n in PARTS)}
  </asset>

  <default>
    <joint damping="20" armature="0.5"/>
    <site group="5" size="0.01" rgba="1 0 0 1"/>
    <default class="collision">
      <geom group="3" rgba="0.8 0.2 0.2 0.5"/>
    </default>
    <default class="visual">
      <geom group="2" contype="0" conaffinity="0" mass="0"/>
    </default>
  </default>

  <worldbody>
    <body name="base" pos="0 0 0">
      <joint name="base_x" type="slide" axis="1 0 0" damping="2000"/>
      <joint name="base_y" type="slide" axis="0 1 0" damping="2000"/>
      <joint name="base_yaw" type="hinge" axis="0 0 1" damping="2000"/>
      {g("box", "collision", name="base_collision", pos=f"0 0 {BASE_TOP/2 + 0.005}", size=f"0.625 0.5 {BASE_TOP/2 - 0.005}", mass=MASS["base"])}
      {mesh("base_lower", "frame")}
      {mesh("base_skirt", "white")}
      {mesh("base_deck", "frame")}
      {mesh("corner_lights", "amber")}
      <body name="turntable" pos="{TT[0]} {TT[1]} {BASE_TOP}">
        <joint name="turntable_yaw" axis="0 0 1" range="-3.14 3.14"/>
        {g("cylinder", "collision", name="turntable_collision", pos="0 0 0.15", size="0.36 0.15", mass=MASS["turntable"] - 40)}
        {g("box", "collision", name="mast_collision", pos="-0.2 -0.22 0.95", size="0.065 0.09 0.65", mass=40)}
        {mesh("turntable", "white")}
        {mesh("turntable_band", "frame")}
        {mesh("mast", "frame", "-0.2 -0.22 0.3")}
        {mesh("mast_light", "light", "-0.2 -0.22 0.3")}
        {mesh("mast_window", "glass", "-0.2 -0.22 0.3")}
        {mesh("shoulder_housing", "frame", "0.05 0.1 0.3")}
        <site name="camera" pos="-0.134 -0.22 1.3"/>
        <body name="upper_arm" pos="0.05 0.1 {SHOULDER_Z}">
          <joint name="shoulder_pitch" axis="0 1 0" range="-3.0 3.0"/>
          {g("capsule", "collision", name="upper_arm_collision", fromto=f"0 0 -0.1 0 0 -{UPPER - 0.1}", size="0.09", mass=MASS["shoulder"] + MASS["upper"])}
          {mesh("upper_arm_shell", "white")}
          {mesh("upper_arm_joint", "frame")}
          <body name="forearm" pos="0 0 -{UPPER}">
            <joint name="elbow_pitch" axis="0 1 0" range="-2.8 2.8"/>
            <joint name="forearm_roll" axis="0 0 1" range="-3.0 3.0"/>
            {g("capsule", "collision", name="forearm_collision", fromto=f"0 0 -0.1 0 0 -{FORE - 0.1}", size="0.07", mass=MASS["fore"])}
            {mesh("forearm_shell", "white")}
            {mesh("forearm_joint", "frame")}
            <body name="wrist" pos="0 0 -{FORE}">
              <joint name="wrist_pitch" axis="0 1 0" range="-2.2 2.2"/>
              <joint name="wrist_yaw" axis="1 0 0" range="-1.6 1.6"/>
              {g("box", "collision", name="wrist_collision", pos="0 0 -0.08", size="0.06 0.06 0.08", mass=MASS["wrist"])}
              {mesh("wrist", "frame")}
              <body name="pad" pos="0 0 -0.16">
                <joint name="pad_roll" axis="0 0 1" range="-3.0 3.0"/>
                {g("box", "collision", name="pad_collision", pos="0.02 0 -0.29", size="0.05 0.21 0.29", mass=MASS["pad"])}
                {mesh("pad_plate", "frame")}
                {mesh("pad_cups", "cups")}
                <site name="pad_face" pos="0.075 0 -0.29"/>
              </body>
            </body>
          </body>
        </body>
      </body>
    </body>
  </worldbody>

  <contact>
    <exclude body1="base" body2="turntable"/>
    <exclude body1="turntable" body2="upper_arm"/>
  </contact>

  <keyframe>
    <key name="home" qpos="0 0 0 {HOME['turntable_yaw']} {HOME['shoulder_pitch']} {HOME['elbow_pitch']} {HOME['forearm_roll']} {HOME['wrist_pitch']} {HOME['wrist_yaw']} {HOME['pad_roll']}"/>
  </keyframe>
</mujoco>
"""

out = Path(__file__).parent / "stretch.xml"
out.write_text(XML)
print("wrote", out)
